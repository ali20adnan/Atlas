export function findByCode(code: string): WarehouseItem | undefined {
  const q = code.trim().toLowerCase();
  if (!q) return undefined;
  return CATALOG.find(
    (item) => item.barcode.toLowerCase() === q || item.sku.toLowerCase() === q || item.id === q,
  );
}

export function searchItems(query: string): WarehouseItem[] {
  const q = query.trim().toLowerCase();
  if (!q) return CATALOG;
  return CATALOG.filter((item) => {
    const hay = [
      item.nameEn,
      item.nameAr,
      item.sku,
      item.barcode,
      item.categoryEn,
      item.categoryAr,
      item.aisle,
      item.rack,
      item.bin,
      `${item.aisle}-${item.rack}-${item.bin}`,
    ]
      .join(' ')
      .toLowerCase();
    return hay.includes(q);
  });
}

export function getItem(id: string): WarehouseItem | undefined {
  return CATALOG.find((item) => item.id === id);
}

